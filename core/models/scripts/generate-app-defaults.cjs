#!/usr/bin/env node
/**
 * Generates the client-wide connection defaults (minimum server version, default URLs) for the native mobile
 * platforms.
 *
 * Input: core/models/src/defaults/AppDefaults.ts
 * Outputs:
 *   - apps/mobile-app/ios/VaultStoreKit/AppInfo.swift (Swift)
 *   - apps/mobile-app/android/app/src/main/java/net/aliasvault/app/utils/AppInfo.kt (Kotlin)
 *
 * TypeScript clients import the constants directly from `@aliasvault/models/defaults`.
 */

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.join(__dirname, '../../..');
const TS_SOURCE_REL = 'core/models/src/defaults/AppDefaults.ts';
const TS_SOURCE = path.join(REPO_ROOT, TS_SOURCE_REL);
const SWIFT_OUTPUT = path.join(REPO_ROOT, 'apps/mobile-app/ios/VaultStoreKit/AppInfo.swift');
const KOTLIN_OUTPUT = path.join(REPO_ROOT, 'apps/mobile-app/android/app/src/main/java/net/aliasvault/app/utils/AppInfo.kt');

/**
 * Parse the `export const NAME = '...';` lines (each with its preceding JSDoc comment) out of the TypeScript
 * source, preserving order.
 */
function parseConstants(source) {
  const constants = [];
  const lines = source.split(/\r?\n/);
  let docLines = [];
  let inDoc = false;

  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith('/**')) {
      inDoc = true;
      docLines = [];
      const inline = trimmed.replace(/^\/\*\*/, '').replace(/\*\/$/, '').trim();
      if (inline) {
        docLines.push(inline);
      }
      if (trimmed.endsWith('*/')) {
        inDoc = false;
      }
      continue;
    }
    if (inDoc) {
      if (trimmed.endsWith('*/')) {
        inDoc = false;
      } else {
        const text = trimmed.replace(/^\*\s?/, '');
        if (text) {
          docLines.push(text);
        }
      }
      continue;
    }

    const constMatch = line.match(/^\s*export const ([A-Z0-9_]+)\s*=\s*'([^']*)'\s*;/);
    if (constMatch) {
      constants.push({ name: constMatch[1], value: constMatch[2], doc: docLines.length > 0 ? docLines : [`${constMatch[1]}.`] });
      docLines = [];
      continue;
    }
    if (trimmed !== '') {
      docLines = [];
    }
  }

  if (constants.length === 0) {
    throw new Error(`No 'export const ... = '<string>';' constants found in ${TS_SOURCE_REL}`);
  }
  return constants;
}

/** Convert to camel case (MIN_SERVER_VERSION -> minServerVersion). */
function toCamelCase(name) {
  return name.toLowerCase().replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
}

/** Escape a string for a Swift or Kotlin double-quoted literal. */
function quote(value) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$');
}

function generateSwift(constants) {
  const members = constants
    .map((c) => `${c.doc.map((line) => `    /// ${line}`).join('\n')}\n    public static let ${toCamelCase(c.name)} = "${quote(c.value)}"`)
    .join('\n\n');

  return `// <auto-generated />
// This file is auto-generated from ${TS_SOURCE_REL}
// Do not edit this file directly. Run 'core/models/build.sh' (or
// 'node core/models/scripts/generate-app-defaults.cjs') to regenerate.

import Foundation

/// Client-wide connection defaults shared by every AliasVault client.
public enum AppInfo {
${members}
}
`;
}

function generateKotlin(constants) {
  const members = constants
    .map((c) => {
      const doc = c.doc.map((line) => `     * ${line}`).join('\n');
      return `    /**\n${doc}\n     */\n    const val ${c.name} = "${quote(c.value)}"`;
    })
    .join('\n\n');

  return `// <auto-generated />
// This file is auto-generated from ${TS_SOURCE_REL}
// Do not edit this file directly. Run 'core/models/build.sh' (or
// 'node core/models/scripts/generate-app-defaults.cjs') to regenerate.

package net.aliasvault.app.utils

/**
 * Client-wide connection defaults shared by every AliasVault client.
 */
object AppInfo {
${members}
}
`;
}

function main() {
  const constants = parseConstants(fs.readFileSync(TS_SOURCE, 'utf8'));
  fs.writeFileSync(SWIFT_OUTPUT, generateSwift(constants));
  fs.writeFileSync(KOTLIN_OUTPUT, generateKotlin(constants));
  console.log(`  ✓ Generated ${path.relative(REPO_ROOT, SWIFT_OUTPUT)}`);
  console.log(`  ✓ Generated ${path.relative(REPO_ROOT, KOTLIN_OUTPUT)}`);
}

main();
